// @effect-diagnostics nodeBuiltinImport:off - standalone file generator, outside an Effect runtime.
import * as NodeFSP from "node:fs/promises";

// The server ships as one bundle, so bundled skills travel as a module, not as files on disk.
const directory = new URL("../../apps/server/src/fork/crews/skills/", import.meta.url);
const skills: Record<string, Record<string, string>> = {};
for (const entry of await NodeFSP.readdir(directory, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const files: Record<string, string> = {};
  const skillDirectory = new URL(`${entry.name}/`, directory);
  for (const file of (await NodeFSP.readdir(skillDirectory)).toSorted()) {
    files[file] = (await NodeFSP.readFile(new URL(file, skillDirectory), "utf8")).replace(
      /\r\n/gu,
      "\n",
    );
  }
  skills[entry.name] = files;
}
await NodeFSP.writeFile(
  new URL("bundledSkills.gen.ts", directory),
  [
    "// Generated by scripts/fork/generate-crew-skills.ts from skills/<name>/*. Do not edit.",
    `export const BUNDLED_SKILLS: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(skills, null, 2)};`,
    "",
  ].join("\n"),
);
